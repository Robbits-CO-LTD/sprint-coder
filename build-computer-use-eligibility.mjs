import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

// ADR v2 D7: which applications are eligible is decided when the native is compiled. The only
// input is the `--eligibility=v1|v2` build argument; no environment variable is read here.
const table = JSON.parse(
  readFileSync(
    join(
      dirname(fileURLToPath(import.meta.url)),
      'apps',
      'desktop',
      'computer-use-native',
      'eligibility.json',
    ),
    'utf8',
  ),
);

const MODES = Object.freeze({ v1: 'v1-allowlist', v2: 'v2-denylist' });

export function parseEligibilityMode(argv, target) {
  const claims = argv.filter(
    (argument) => argument === '--eligibility' || argument.startsWith('--eligibility='),
  );
  if (claims.length === 0) return MODES.v1;
  if (claims.length > 1)
    throw new Error('Computer Use native --eligibility was given more than once');
  const value = claims[0].startsWith('--eligibility=')
    ? claims[0].slice('--eligibility='.length)
    : '';
  if (!Object.hasOwn(MODES, value))
    throw new Error('Computer Use native --eligibility accepts only v1 or v2');
  const mode = MODES[value];
  if (mode === MODES.v2 && target === 'win32')
    throw new Error(
      'Computer Use native --eligibility=v2 is unsupported on Windows until S5 (no deny-list there yet)',
    );
  return mode;
}

export function eligibilityDeclaration(mode, platform) {
  if (!Object.values(MODES).includes(mode))
    throw new Error('Computer Use native eligibility mode is unknown');
  if (!Object.hasOwn(table.ticketRequired, platform))
    throw new Error('Computer Use native eligibility platform is unknown');
  return {
    mode,
    rulesetVersion: table.versions.rulesetVersion,
    classifierVersion: table.versions.classifierVersion,
    lexiconVersion: table.versions.lexiconVersion,
    ticketRequired: table.ticketRequired[platform],
  };
}

/** The C++ side of a declaration: macros read by `computer_use_native_eligibility.h`. */
export function eligibilityBuildHeader(declaration) {
  return [
    '#pragma once',
    '// Generated by build-computer-use-native.mjs. Do not edit; do not commit.',
    `#define SPRINT_CODER_ELIGIBILITY_V2 ${declaration.mode === MODES.v2 ? 1 : 0}`,
    `#define SPRINT_CODER_ELIGIBILITY_RULESET_VERSION ${declaration.rulesetVersion}`,
    `#define SPRINT_CODER_ELIGIBILITY_CLASSIFIER_VERSION ${declaration.classifierVersion}`,
    `#define SPRINT_CODER_ELIGIBILITY_LEXICON_VERSION ${declaration.lexiconVersion}`,
    `#define SPRINT_CODER_ELIGIBILITY_TICKET_REQUIRED ${declaration.ticketRequired ? 1 : 0}`,
    '',
  ].join('\n');
}
